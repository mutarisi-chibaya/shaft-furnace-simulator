"""Comparison of the whole-furnace model with REDUCTOR case A (Milestone 5).

Reference data (tests/data, generated by scripts):
- ``reference_model_marsigny2025b_caseA.csv``: Table 1 outputs (top gas, DRI, metallisation,
  GUD), scripts/extract_reductor_table1.py.
- ``reference_model_marsigny2025b_caseA_profiles.csv``: cross-section averages of the 2D maps
  (Figs. 3, 4, 6-9), scripts/digitize_reductor_maps.py. Each value is known only to within
  its colour band, so a profile point is an interval [mean_lo, mean_hi].

Coordinates: REDUCTOR's z is the height above the bottom of the upper cylinder (top 15 m,
bustle 4.9 m, solid outlet -10 m); the model's depth d below the top maps to z = 15 - d.

Units: model quantities are converted to the units of the reference files (degC, %, t/h).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd
from numpy.typing import NDArray

from shaftsim import energy as en
from shaftsim import pellet as pl

FloatArray = NDArray[np.float64]
KELVIN = 273.15
#: Model solid phases -> REDUCTOR map names (REDUCTOR's "FeO" is the wustite phase).
PHASES = {"Fe2O3": "w_Fe2O3", "Fe3O4": "w_Fe3O4", "Fe0.95O": "w_FeO", "Fe": "w_Fe"}


def load_reference_outputs(path: str | Path) -> dict[str, float]:
    """Table 1 values by key, in the units of the file (see its header)."""
    d = pd.read_csv(path, comment="#")
    return {str(k): float(v) for k, v in zip(d.key, d.value, strict=True)}


def load_reference_profiles(path: str | Path) -> pd.DataFrame:
    """Digitised cross-section averages: columns quantity, z, mean, mean_lo, mean_hi, ..."""
    return pd.read_csv(path, comment="#")


def model_outputs(prob: en.ThermalProblem, sol: en.ThermalSolution) -> dict[str, float]:
    """Model values with the keys and units of :func:`load_reference_outputs`."""
    s = sol.species
    case = prob.case.shaft
    w = pl.solid_mass_fractions(case.pellet, s.X_steps[:, -1])
    return {
        "top_gas_flow": float(prob.grid.F[0]),
        "top_gas_T": sol.T_top_gas - KELVIN,
        "top_gas_x_H2": 100.0 * float(s.x_H2[0]),
        "top_gas_x_H2O": 100.0 * float(s.x_H2O[0]),
        "top_gas_x_N2": 100.0 * (1.0 - float(prob.grid.g[0])),
        "dri_flow": s.product_flow * 3.6,  # kg/s -> t/h
        "dri_T": sol.T_solid_out - KELVIN,
        "dri_w_Fe2O3": 100.0 * float(w["Fe2O3"]),
        "dri_w_Fe3O4": 100.0 * float(w["Fe3O4"]),
        "dri_w_FeO": 100.0 * float(w["Fe0.95O"]),
        "dri_w_Fe": 100.0 * float(w["Fe"]),
        "dri_w_gangue": 100.0 * float(w["gangue"]),
        "metallization": 100.0 * s.metallization,
        "gud": s.gud,
    }


def model_profiles(prob: en.ThermalProblem, sol: en.ThermalSolution) -> pd.DataFrame:
    """Model profiles in the reference quantities, one row per cell, z = 15 m - depth."""
    s = sol.species
    case = prob.case.shaft
    z_top = case.segments[0].length + case.segments[1].length if case.segments else case.height
    w = pl.solid_mass_fractions(case.pellet, s.X_steps)
    out = pd.DataFrame(
        {
            "z": z_top - prob.grid.z,
            "T_solid": sol.Ts - KELVIN,
            "T_gas": sol.Tg - KELVIN,
            "x_H2": s.x_H2,
        }
    )
    for k, name in PHASES.items():
        out[name] = w[k]
    return out


@dataclass(frozen=True)
class OutputComparison:
    """One Table 1 quantity: reference, model and difference (model - reference)."""

    key: str
    reference: float
    model: float

    @property
    def difference(self) -> float:
        """Model minus reference, in the units of the reference."""
        return self.model - self.reference

    @property
    def relative(self) -> float:
        """Difference relative to the reference [-] (nan if the reference is 0)."""
        return self.difference / self.reference if self.reference != 0 else float("nan")


def compare_outputs(ref: dict[str, float], model: dict[str, float]) -> list[OutputComparison]:
    """Table 1 comparison for every key the model provides."""
    return [OutputComparison(k, ref[k], model[k]) for k in model if k in ref]


@dataclass(frozen=True)
class ProfileComparison:
    """Agreement of one axial profile with the digitised reference.

    Attributes:
        quantity: Reference quantity name.
        n_points: Reference points compared.
        within_band: Fraction of points where the model lies inside the reference band.
        mean_excess: Mean distance of the model outside the band (0 inside) [units].
        max_excess: Largest such distance [units].
        rms_midpoint: RMS of model - band-midpoint average [units].
    """

    quantity: str
    n_points: int
    within_band: float
    mean_excess: float
    max_excess: float
    rms_midpoint: float


def compare_profile(
    ref: pd.DataFrame, model: pd.DataFrame, quantity: str, z_range: tuple[float, float]
) -> ProfileComparison:
    """Compare the model profile of ``quantity`` with the reference band over z_range [m].

    The model is interpolated linearly (cell centres) to the reference heights.
    """
    r = ref[(ref.quantity == quantity) & (ref.z >= z_range[0]) & (ref.z <= z_range[1])]
    zm = model.z.to_numpy()
    order = np.argsort(zm)
    v = np.interp(r.z.to_numpy(), zm[order], model[quantity].to_numpy()[order])
    lo, hi = r.mean_lo.to_numpy(), r.mean_hi.to_numpy()
    excess = np.maximum(lo - v, 0.0) + np.maximum(v - hi, 0.0)
    return ProfileComparison(
        quantity=quantity,
        n_points=len(r),
        within_band=float(np.mean(excess == 0.0)),
        mean_excess=float(np.mean(excess)),
        max_excess=float(np.max(excess)),
        rms_midpoint=float(np.sqrt(np.mean((v - r["mean"].to_numpy()) ** 2))),
    )
