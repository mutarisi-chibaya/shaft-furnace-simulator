"""Extract Lennard-Jones (12-6) collision integrals from Cantera's MMCollisionInt.cpp.

Cantera (v3.0.0, BSD-3) tabulates the reduced collision integral Omega(2,2)* and the ratio
A* = Omega(2,2)*/Omega(1,1)* as functions of the reduced temperature T* = kT/eps, for several
values of the dipole parameter delta* (Monchick & Mason 1961). This script copies the
delta* = 0 column (non-polar Lennard-Jones potential), which is what the Chapman-Enskog
formulas in shaftsim.transport use, into data/collision_integrals.csv.

Usage:
    python scripts/extract_collision_integrals.py
"""

from __future__ import annotations

import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "references" / "mmcollisionint_cantera_v3.0.0.cpp"
N_DELTA = 8  # columns per row (delta* = 0, 0.25, ..., 2.5); column 0 is delta* = 0


def array(text: str, name: str) -> list[float]:
    m = re.search(rf"MMCollisionInt::{name}\[[^\]]*\]\s*=\s*\{{(.*?)\}};", text, re.S)
    if not m:
        raise ValueError(f"array {name} not found")
    return [float(v) for v in re.findall(r"-?\d+\.?\d*(?:[eE][-+]?\d+)?", m.group(1))]


def main() -> None:
    text = SRC.read_text(encoding="utf-8")
    tstar22 = array(text, "tstar22")
    omega22 = array(text, "omega22_table")
    tstar = array(text, "tstar")
    astar = array(text, "astar_table")
    if len(omega22) != N_DELTA * len(tstar22) or len(astar) != N_DELTA * len(tstar):
        raise ValueError("unexpected table sizes")
    o22 = {t: omega22[N_DELTA * i] for i, t in enumerate(tstar22)}
    a = {t: astar[N_DELTA * i] for i, t in enumerate(tstar)}
    common = [t for t in tstar22 if t in a]  # T* = 0.1 ... 100
    out = ROOT / "data" / "collision_integrals.csv"
    with open(out, "w", newline="", encoding="utf-8") as fh:
        fh.write("# Lennard-Jones 12-6 collision integrals, delta* = 0 (non-polar).\n")
        fh.write("# Source: Cantera v3.0.0 src/transport/MMCollisionInt.cpp (Monchick & Mason\n")
        fh.write("# 1961). Generated by scripts/extract_collision_integrals.py. omega11 =\n")
        fh.write("# omega22 / astar.\n")
        w = csv.writer(fh)
        w.writerow(["tstar", "omega22", "astar", "omega11"])
        for t in common:
            w.writerow([t, o22[t], a[t], round(o22[t] / a[t], 6)])
    print(f"wrote {out.relative_to(ROOT)} ({len(common)} rows, T* {common[0]}-{common[-1]})")


if __name__ == "__main__":
    main()
