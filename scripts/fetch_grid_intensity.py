"""Electricity grid CO2 intensities from Ember's yearly electricity data (CC BY 4.0).

Usage:
    python scripts/fetch_grid_intensity.py

Downloads Ember's global yearly generation release (one CSV, ~15 MB) to
references/ember_generation_yearly_global.csv (not committed) and writes
data/grid_intensity.yaml (generated, do not edit) with the "Total generation" emissions
intensity of each area in AREAS for every year from FIRST_YEAR, and its latest year.

Ember's intensities are life-cycle values (gCO2e/kWh, including upstream emissions of each
source), as documented at https://ember-energy.org/data/yearly-electricity-data/.
"""

from __future__ import annotations

import csv
import datetime as dt
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
URL = "https://files.ember-energy.org/public-downloads/generation/outputs/release_generation_yearly_global.csv"
RAW = ROOT / "references" / "ember_generation_yearly_global.csv"
OUT = ROOT / "data" / "grid_intensity.yaml"
USER_AGENT = "shaftsim-reference-fetch/0.1 (research script)"
#: area name in the file -> yaml key; France as an example of a low-carbon grid
AREAS = {"South Africa": "south_africa", "World": "world", "France": "france"}
FIRST_YEAR = 2015


def download() -> str:
    req = urllib.request.Request(URL, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=120) as r:
        modified = str(r.headers.get("Last-Modified", "unknown"))
        RAW.parent.mkdir(exist_ok=True)
        RAW.write_bytes(r.read())
    return modified


def main() -> None:
    modified = download()
    series: dict[str, dict[int, float]] = {k: {} for k in AREAS.values()}
    with open(RAW, encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            key = AREAS.get(row["Area"])
            if key is None or row["Electricity source"] != "Total generation":
                continue
            year = int(row["Year"])
            val = row["Emissions intensity (gCO2e/kWh)"]
            if year >= FIRST_YEAR and val:
                series[key][year] = float(val)
    for area, s in series.items():
        if not s:
            raise SystemExit(f"no intensity found for {area}")
    lines = [
        "# Electricity grid CO2 intensity, GENERATED by scripts/fetch_grid_intensity.py (do not",
        "# edit). Ember, yearly electricity data, 'Total generation' rows, emissions intensity",
        "# (life-cycle, gCO2e/kWh), CC BY 4.0.",
        f"# Source file: {URL}",
        f"# Last-Modified of the file: {modified}; downloaded {dt.date.today().isoformat()}.",
        "# value in kg CO2e per J of electricity (SI); g/kWh / 3.6e9.",
        "areas:",
    ]
    for name, key in AREAS.items():
        s = series[key]
        latest = max(s)
        lines.append(f"  {key}:")
        lines.append(f'    name: "{name}"')
        lines.append(
            f"    latest: {{year: {latest}, value: {s[latest] / 3.6e9:.6e}, unit: kg/J, "
            f"g_per_kWh: {s[latest]:g}, source: Ember2026-yearly}}"
        )
        lines.append(
            "    g_per_kWh_by_year: {" + ", ".join(f"{y}: {s[y]:g}" for y in sorted(s)) + "}"
        )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    for key, s in series.items():
        latest = max(s)
        print(f"{key}: {s[latest]:g} gCO2e/kWh in {latest}")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
